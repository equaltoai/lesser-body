func mcpJSONSpec() fileSpec {
	return fileSpec{
		path:         ".mcp.json",
		role:         "mcp_client_config",
		kind:         "config",
		mediaType:    "application/json",
		required:     true,
		description:  "MCP HTTP client config pointing at the actor-specific Lesser endpoint; auth is discovered through standard Lesser OAuth metadata.",
		templateName: "mcp_json.v1",
		renderer:     renderMCPJSON,
	}
}

func installMarkerSpec() fileSpec {
	return fileSpec{
		path:         installMarkerPath,
		role:         "install_marker",
		kind:         "metadata",
		mediaType:    "application/json",
		required:     true,
		description:  "Deterministic install marker metadata for local verification and safe re-application.",
		templateName: "install_marker.v1",
		renderer:     renderInstallMarker,
	}
}

func installGuideSpec() fileSpec {
	return fileSpec{
		path:         "INSTALL.md",
		role:         "merge_instructions",
		kind:         "documentation",
		mediaType:    "text/markdown; charset=utf-8",
		required:     true,
		description:  "Human-readable local merge and checksum verification guidance for the pack.",
		templateName: "install_guide.v1",
		template: `# Lesser local install pack

Profile: ` + "`{{.Profile}}`" + `  
MCP server name: ` + "`{{.MCPServerName}}`" + `  
MCP endpoint: ` + "`{{.MCPEndpointURL}}`" + `

## Verify before merging

1. Read ` + "`MANIFEST.json`" + `.
2. For every ` + "`manifest_entries[]`" + ` item, compute SHA-256 over the ZIP entry bytes and compare it to ` + "`checksum`" + `.
3. Merge only the required config/instruction files that match the manifest.

## Authentication posture

The rendered MCP config uses the actor-specific HTTP endpoint and standard Lesser OAuth protected-resource metadata:

` + "`{{.OAuthMetadataURL}}`" + `

This pack intentionally contains no bearer token, access lease, client secret, installer grant URL, or raw grant token.
`,
	}
}

func (l layout) mergeInstructions(serverName string) []MergeInstruction {
	switch l.profile {
	case ProfileClaudeCode:
		return []MergeInstruction{
			{Path: ".mcp.json", Action: "merge_mcp_server", Description: "Merge the mcpServers entry keyed by " + serverName + " into the local Claude Code MCP config."},
			{Path: "CLAUDE.md", Action: "review_then_write", Description: "Review the rendered Claude Code instructions before writing or replacing local instructions."},
			{Path: installMarkerPath, Action: "write_marker", Description: "Write after checksum verification so future installs can identify this pack."},
		}
	case ProfileCodex:
		return []MergeInstruction{
			{Path: ".mcp.json", Action: "merge_mcp_server", Description: "Merge the mcpServers entry keyed by " + serverName + " into any JSON MCP config used by the local host."},
			{Path: ".codex/config.toml", Action: "merge_mcp_server", Description: "Merge the mcp_servers table for " + serverName + " into Codex config."},
			{Path: "AGENTS.md", Action: "review_then_write", Description: "Review the rendered Codex instructions before writing or replacing local instructions."},
			{Path: installMarkerPath, Action: "write_marker", Description: "Write after checksum verification so future installs can identify this pack."},
		}
	default:
		return nil
	}
}
