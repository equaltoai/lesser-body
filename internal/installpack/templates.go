package installpack

const installMarkerPath = ".lesser-body/install-marker.json"

type layout struct {
	profile Profile
	files   []fileSpec
}

type fileSpec struct {
	path         string
	role         string
	kind         string
	mediaType    string
	required     bool
	description  string
	templateName string
	template     string
	renderer     func(templateData) ([]byte, error)
}

type renderedFile struct {
	spec fileSpec
	body []byte
}

type templateData struct {
	Profile           string
	StageDomain       string
	Actor             string
	Namespace         string
	Account           string
	PackID            string
	PackDigest        string
	MCPServerName     string
	MCPEndpointURL    string
	OAuthMetadataURL  string
	AuthorizationURL  string
	AgentSoul         string
	AgentInstructions string
}

func defaultLayouts() map[Profile]layout {
	return map[Profile]layout{
		ProfileClaudeCode: claudeCodeLayout(),
		ProfileCodex:      codexLayout(),
	}
}

func claudeCodeLayout() layout {
	return layout{profile: ProfileClaudeCode, files: []fileSpec{
		mcpJSONSpec(),
		{
			path:         "CLAUDE.md",
			role:         "agent_instructions",
			kind:         "instructions",
			mediaType:    "text/markdown; charset=utf-8",
			required:     true,
			description:  "Claude Code local instructions rendered from explicit Ba install-pack inputs.",
			templateName: "claude_code_instructions.v1",
			template: `# Lesser agent {{.Actor}}

This local workspace is configured to use the Lesser MCP server ` + "`{{.MCPServerName}}`" + `.

- MCP endpoint: ` + "`{{.MCPEndpointURL}}`" + `
- OAuth: use Lesser OAuth protected-resource discovery at ` + "`{{.OAuthMetadataURL}}`" + `.
- Do not add hardcoded bearer tokens, access leases, or static Authorization headers to this pack.

## Agent soul

{{.AgentSoul}}

## Agent instructions

{{.AgentInstructions}}
`,
		},
		installMarkerSpec(),
		installGuideSpec(),
	}}
}

